-- 출시 코호트 오픈: 서울 학교 64곳의 첫 카드를 2026-11-02(월) 07:00(Asia/Seoul)에 연다.
-- 사용자 결정(2026-10-20 "65개 학교 다 막아야 하는데? 추천대로 가자"): 출시일에 가입해도 그날 바로 카드가
-- 열리지 않고, 홈은 오픈 대기(카운트다운)를 보인다. 시험 학교(region_group = 'e2e', 심사 계정 소속)는 일부러 건드리지 않는다 —
-- 심사원이 카운터 화면이 아니라 전체 기능을 봐야 한다.
-- 시각은 check `universities_card_opens_monday_0700`(서울 월요일 07:00)을 통과한다(운영에서 읽기 전용으로 검증함).
-- 이미 날짜가 있는 학교는 덮어쓰지 않아 다시 적용해도 같은 결과다(멱등). 스키마 변경 없음.
-- 적용 전 초안 — 사용자 승인 문장을 받은 뒤 대장이 한 번만 적용한다.
update public.universities
   set card_opens_at = timestamptz '2026-11-02 07:00:00+09'
 where region_group = 'seoul'
   and card_opens_at is null;
