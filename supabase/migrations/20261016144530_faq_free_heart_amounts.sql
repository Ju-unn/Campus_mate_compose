update public.faq
set answer = replace(replace(replace(answer,
               '에브리타임 홍보 글 인증은 월 1회 50하트', '에브리타임 홍보 글 인증은 월 1회 40하트'),
               '학교 단톡방 공유 인증은', '단톡방 공유 인증은'),
               '하루 한 번 10하트, 한 주에 최대 30하트', '하루 한 번 5하트, 한 주에 최대 15하트'),
    updated_at = now()
where category = 'heart_payment'
  and question = '하트를 무료로 얻는 방법이 있나요?'
  and (answer like '%에브리타임 홍보 글 인증은 월 1회 50하트%'
       or answer like '%학교 단톡방 공유 인증은%'
       or answer like '%하루 한 번 10하트, 한 주에 최대 30하트%');
